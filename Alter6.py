#Introducir la medida en números enteros de un triángulo y visualizar si es
#equilátero o no.
n1=int(input("Introduce lado 1:"))
n2=int(input("Introduce lado 2:"))
n3=int(input("Introduce lado 3:"))
if n1==n2==n3:
    print ("Tu triángulo es equilátero")
else:
    print ("Tu triángulo no es equilátero")